export function getSurahDisplayName(surah: SurahInfo, lang: AppLanguage): string {
  if (lang === "en") return SURAH_NAMES_EN[surah.number] ?? surah.nameAlt ?? surah.name;
  return surah.name;
}

export function getSurahEnglishMeaning(surahNumber: number): string {
  return SURAH_MEANINGS_EN[surahNumber] ?? "";
}
